    /** Valida los datos y conecta fuera del hilo de eventos de Swing. */
    private void conectar() {
        final ChatCliente chat;
        try {
            int puerto = Integer.parseInt(txtPuerto.getText().trim());
            if (puerto < 1 || puerto > 65535 || txtIp.getText().trim().isEmpty()
                    || txtNombre.getText().trim().isEmpty()) {
                throw new IllegalArgumentException("Datos incompletos");
            }
            chat = new ChatCliente(txtIp.getText(), puerto, txtNombre.getText());
        } catch (IllegalArgumentException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Revise IP, nombre y puerto (1 a 65535).", "Datos inválidos", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        conectando = true;
        aceptar.setEnabled(false); aceptar.setText("Conectando...");
        new javax.swing.SwingWorker<Void, Void>() {
            /** @return null al completar la conexión
             * @throws java.io.IOException si el servidor no está disponible */
            @Override protected Void doInBackground() throws java.io.IOException {
                chat.conectar(); return null;
            }
            /** Abre el chat o permite corregir los datos y reintentar. */
            @Override protected void done() {
                conectando = false;
                aceptar.setEnabled(true); aceptar.setText("Aceptar");
                try { get(); chat.setVisible(true); dispose(); }
                catch (Exception ex) {
                    chat.dispose();
                    Throwable causa = ex.getCause() == null ? ex : ex.getCause();
                    javax.swing.JOptionPane.showMessageDialog(LoginCliente.this,
                        "No se pudo conectar: " + causa.getMessage(), "Conexión", javax.swing.JOptionPane.ERROR_MESSAGE);
                }
            }
        }.execute();
    }

