    public ChatCliente(String ip, int puerto, String nombre) {
        this();
        cliente = new Chat.Cliente(ip, puerto, nombre, this);
        setTitle("Chat - " + cliente.getUsuario());
        lblTitulo.setText(cliente.getUsuario());
    }



    /**
     * Conecta la sesión; debe llamarse desde un hilo de trabajo.
     * @throws java.io.IOException si no se logra conectar
     */
    public void conectar() throws java.io.IOException {
        conectado = true;
        try { cliente.conectar(); }
        catch (java.io.IOException ex) { conectado = false; throw ex; }
        javax.swing.SwingUtilities.invokeLater(() -> txtEntrada.setEnabled(conectado));
    }

    /** Envía el texto con Enter; chao cierra la sesión. */
    private void enviarMensaje() {
        String texto = txtEntrada.getText().trim();
        if (texto.isEmpty()) return;
        if ("chao".equalsIgnoreCase(texto)) { cliente.desconectar(); dispose(); return; }
        txtEntrada.setText("");
        txtEntrada.setEnabled(false);
        new javax.swing.SwingWorker<Void, Void>() {
            /** @return null después de enviar
             * @throws java.io.IOException si se perdió la conexión */
            @Override protected Void doInBackground() throws java.io.IOException {
                cliente.enviarMensaje(texto); return null;
            }
            /** Refleja el mensaje local únicamente cuando se pudo enviar. */
            @Override protected void done() {
                try { get(); onMensajeRecibido(cliente.getUsuario() + "--> " + texto); txtEntrada.setEnabled(conectado); txtEntrada.requestFocusInWindow(); }
                catch (Exception ex) { onDesconectado(); }
            }
        }.execute();
    }

    /** Procesa el dato indicado.
     * @param mensaje línea que se añade al historial en el hilo de Swing
     */
    @Override public void onMensajeRecibido(String mensaje) {
        javax.swing.SwingUtilities.invokeLater(() -> {
            areaMensajes.append(mensaje + "\n");
            areaMensajes.setCaretPosition(areaMensajes.getDocument().getLength());
        });
    }

    /** Desactiva la entrada cuando el servidor cierra o se pierde la conexión. */
    @Override public void onDesconectado() {
        conectado = false;
        javax.swing.SwingUtilities.invokeLater(() -> {
            areaMensajes.append("Desconectado del servidor.\n");
            txtEntrada.setEnabled(false);
        });
    }

